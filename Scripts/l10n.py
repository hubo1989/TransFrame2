#!/usr/bin/env python3
"""String Catalog tooling for TransFrame 2 (SPEC §05 §7, ADR-0012).

  l10n.py gen              regenerate typed keys from the catalog
  l10n.py check            completeness gate (exit 1 on any violation)
  l10n.py add KEY EN       add an English source string (other languages left missing)
  l10n.py merge FILE       merge {"key": {"lang": "value"}} into the catalog
  l10n.py missing [FILE]   write {"key": {"en": ..., "missing": [langs]}} for translators
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = os.path.join(ROOT, "Packages", "TransFrameKit")
CATALOG = os.path.join(PKG, "Sources", "TFLocalization", "Resources", "Localizable.xcstrings")
KEYS_SWIFT = os.path.join(PKG, "Sources", "TFLocalization", "L10nKeys.generated.swift")
EXEMPTIONS = os.path.join(ROOT, "Scripts", "l10n-exemptions.txt")
LANGS = ["en", "zh-Hans", "de", "es", "fr", "it", "ja", "ko", "pt", "ru"]
# Keys resolved from Domain values at runtime; their presence is verified by Swift tests.
DYNAMIC_PREFIXES = ("error.", "color.", "undo.", "provenance.sent.", "engine.name.", "language.", "settings.page.", "tool.", "hotkey.", "category.", "sensitive.", "smartAction.", "tone.", "history.kind.", "stage.")
PLACEHOLDER = re.compile(r"%(?:\d+\$)?(?:lld|ld|d|@|f|\.\d+f|s|u)")


def load():
    with open(CATALOG, encoding="utf-8") as f:
        return json.load(f)


def save(cat):
    cat["strings"] = dict(sorted(cat["strings"].items()))
    with open(CATALOG, "w", encoding="utf-8") as f:
        json.dump(cat, f, ensure_ascii=False, indent=2, sort_keys=False)
        f.write("\n")


def values(entry, lang):
    """All string values for a language (plural variants flattened)."""
    loc = entry.get("localizations", {}).get(lang)
    if not loc:
        return []
    if "stringUnit" in loc:
        return [loc["stringUnit"].get("value", "")]
    out = []
    for variants in loc.get("variations", {}).values():
        for v in variants.values():
            out.append(v.get("stringUnit", {}).get("value", ""))
    return out


def camel(key):
    parts = re.split(r"[._\-]", key)
    head, rest = parts[0], parts[1:]
    name = head[:1].lower() + head[1:] + "".join(p[:1].upper() + p[1:] for p in rest if p)
    if name[0].isdigit():
        name = "k" + name
    return name


def gen():
    cat = load()
    lines = [
        "// Generated by Scripts/l10n.py gen. Do not edit.",
        "// swiftlint:disable all",
        "",
        "public extension L10nKey {",
    ]
    for key in sorted(cat["strings"]):
        lines.append(f'    static let {camel(key)} = L10nKey("{key}")')
    lines.append("}")
    lines.append("")
    with open(KEYS_SWIFT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"generated {len(cat['strings'])} keys")


def swift_sources(*dirs):
    for d in dirs:
        for base, _, files in os.walk(d):
            if "/.build" in base or "Tests" in base.split(os.sep):
                continue
            for name in files:
                if name.endswith(".swift") and not name.endswith(".generated.swift"):
                    yield os.path.join(base, name)


def exemptions():
    if not os.path.exists(EXEMPTIONS):
        return []
    out = []
    with open(EXEMPTIONS, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(line)
    return out


UI_LITERAL = re.compile(
    r'\b(Text|Button|Label|Toggle|Picker|TextField|SecureField|Section|Menu|LabeledContent|Stepper|Link)\s*\(\s*"(?!\\\()([^"\\]|\\.)+"'
    r'|\.(help|accessibilityLabel|accessibilityHint|navigationTitle|alert|confirmationDialog)\s*\(\s*"(?!\\\()([^"\\]|\\.)+"'
    r'|NSMenuItem\s*\(\s*title:\s*"([^"\\]|\\.)+"'
    r'|\.title\s*=\s*"([^"\\]|\\.)+"'
)
CJK = re.compile(r'"[^"\n]*[\u3040-\u30ff\u3400-\u9fff\uac00-\ud7af][^"\n]*"')


def check():
    cat = load()
    strings = cat["strings"]
    errors = []
    # 1. every key has a non-empty value in every language
    for key, entry in strings.items():
        for lang in LANGS:
            vals = values(entry, lang)
            if not vals or any(not v.strip() for v in vals):
                errors.append(f"missing translation: {key} [{lang}]")
    # 4. placeholders consistent with English
    for key, entry in strings.items():
        en = values(entry, "en")
        if not en:
            continue
        ref = sorted(PLACEHOLDER.findall(en[-1]))
        for lang in LANGS[1:]:
            for v in values(entry, lang):
                got = sorted(PLACEHOLDER.findall(v))
                if got and got != ref:
                    errors.append(f"placeholder mismatch: {key} [{lang}] {got} != {ref}")
    # generated keys up to date
    if os.path.exists(KEYS_SWIFT):
        with open(KEYS_SWIFT, encoding="utf-8") as f:
            generated = set(re.findall(r'L10nKey\("([^"]+)"\)', f.read()))
        if generated != set(strings):
            errors.append("L10nKeys.generated.swift is stale; run Scripts/l10n.py gen")
    # 2. referenced / orphan keys
    sources = list(swift_sources(os.path.join(PKG, "Sources"), os.path.join(ROOT, "App")))
    corpus = ""
    for path in sources:
        with open(path, encoding="utf-8") as f:
            corpus += f.read() + "\n"
    for key in strings:
        if key.startswith(DYNAMIC_PREFIXES):
            continue
        name = camel(key)
        if not re.search(r"\.%s\b" % re.escape(name), corpus) and f'"{key}"' not in corpus:
            errors.append(f"orphan key (never referenced): {key}")
    for match in re.finditer(r'L10nKey\("([^"]+)"\)', corpus):
        if match.group(1) not in strings:
            errors.append(f"unknown key referenced: {match.group(1)}")
    # 3. no UI literals in App/ and Feature modules
    allowed = exemptions()
    ui_dirs = [os.path.join(ROOT, "App")] + [
        os.path.join(PKG, "Sources", d)
        for d in os.listdir(os.path.join(PKG, "Sources"))
        if d.endswith("Feature") or d in ("TFWorkspaceUI", "TFDesignSystem")
    ]
    for path in swift_sources(*ui_dirs):
        rel = os.path.relpath(path, ROOT)
        with open(path, encoding="utf-8") as f:
            for number, line in enumerate(f, 1):
                stripped = line.strip()
                if stripped.startswith("//"):
                    continue
                if any(a in f"{rel}:{number}" or (a in rel and a.endswith("*")) or a in stripped for a in allowed):
                    continue
                if UI_LITERAL.search(line) and "verbatim:" not in line:
                    errors.append(f"UI literal: {rel}:{number}: {stripped[:100]}")
                elif CJK.search(line):
                    errors.append(f"CJK literal: {rel}:{number}: {stripped[:100]}")
    for e in errors:
        print(e)
    print(f"check-l10n: {len(strings)} keys, {len(LANGS)} languages, {len(errors)} problems")
    return 1 if errors else 0


def add(key, english):
    cat = load()
    entry = cat["strings"].setdefault(key, {"localizations": {}})
    entry.setdefault("localizations", {})["en"] = {"stringUnit": {"state": "translated", "value": english}}
    save(cat)


def merge(path):
    with open(path, encoding="utf-8") as f:
        incoming = json.load(f)
    cat = load()
    for key, langs in incoming.items():
        entry = cat["strings"].setdefault(key, {"localizations": {}})
        locs = entry.setdefault("localizations", {})
        for lang, value in langs.items():
            if lang not in LANGS:
                continue
            if isinstance(value, dict):  # plural: {"one": ..., "other": ...}
                locs[lang] = {"variations": {"plural": {k: {"stringUnit": {"state": "translated", "value": v}} for k, v in value.items()}}}
            else:
                locs[lang] = {"stringUnit": {"state": "translated", "value": value}}
    save(cat)
    print(f"merged {len(incoming)} keys")


def missing(out):
    cat = load()
    result = {}
    for key, entry in cat["strings"].items():
        gaps = [lang for lang in LANGS[1:] if not values(entry, lang)]
        if gaps:
            loc = entry.get("localizations", {}).get("en", {})
            en = loc.get("stringUnit", {}).get("value") if "stringUnit" in loc else {
                k: v["stringUnit"]["value"] for k, v in loc.get("variations", {}).get("plural", {}).items()
            }
            result[key] = {"en": en, "missing": gaps}
    text = json.dumps(result, ensure_ascii=False, indent=2)
    if out:
        with open(out, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    else:
        print(text)
    print(f"{len(result)} keys need translations", file=sys.stderr)


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "gen":
        gen()
    elif cmd == "check":
        sys.exit(check())
    elif cmd == "add":
        add(sys.argv[2], sys.argv[3])
    elif cmd == "merge":
        merge(sys.argv[2])
    elif cmd == "missing":
        missing(sys.argv[2] if len(sys.argv) > 2 else None)
    else:
        print(__doc__)
        sys.exit(2)
